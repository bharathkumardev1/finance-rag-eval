"""Write results/RESULTS.md from results/eval.json."""

from __future__ import annotations

from pathlib import Path


def _pct(x: float | None) -> str:
    return "" if x is None else f"{x:.2f}"


def _ci(ci: list[float]) -> str:
    return f"{ci[0]:.2f}–{ci[1]:.2f}"


def _rows(results: dict, split: str) -> list[dict]:
    return [r for r in results["table"] if r["split"] == split]


def table(results: dict, split: str, configs: list[str] | None = None) -> str:
    head = ("| Config | Hit@1 | Hit@5 | Hit@10 (95% CI) | MRR@10 | Recall@10 | Right filing@10 "
            "| p50 ms | p95 ms |\n|---|---|---|---|---|---|---|---|---|\n")
    lines = []
    for r in _rows(results, split):
        if configs is not None and r["config"] not in configs:
            continue
        lines.append(
            f"| `{r['config']}` | {_pct(r['hit@1'])} | {_pct(r['hit@5'])} | "
            f"{_pct(r['hit@10'])} ({_ci(r['hit@10_ci95'])}) | {r['mrr@10']:.3f} | "
            f"{_pct(r['recall@10'])} | {_pct(r['doc_hit@10'])} | {r['p50_ms']:.1f} | "
            f"{r['p95_ms']:.1f} |")
    return head + "\n".join(lines) + "\n"


def write_markdown(results: dict, path: Path) -> None:
    meta = results["meta"]
    parts = [
        "# Results\n",
        f"Generated by `finrag eval` at commit `{meta['git_sha']}`"
        f"{' (uncommitted changes)' if meta['git_dirty'] else ''} on {meta['date']}. "
        f"{meta['filings']} filings, {meta['pages']:,} pages"
        + (f", {meta['dense_windows']:,} MiniLM windows" if meta.get("dense_windows") else "")
        + f". {meta['cpu']} ({meta['cpus']} CPUs), Python {meta['python']}, "
        f"onnxruntime {meta['onnxruntime']}. Latency is in-process, one thread, per query.\n",
        f"Headline configuration (picked on dev): `{results['headline']}`.\n",
        f"## Test split ({meta['test']} questions)\n",
        table(results, "test"),
        f"## Dev split ({meta['dev']} questions)\n",
        table(results, "dev"),
        "## Paired comparisons on test (bootstrap, 10,000 resamples)\n",
        "| A | B | Metric | A − B | 95% CI | A better | B better |\n|---|---|---|---|---|---|---|\n"
        + "\n".join(
            f"| `{c['a']}` | `{c['b']}` | {c['metric']} | {c['diff']:+.3f} | "
            f"{c['ci95'][0]:+.3f} to {c['ci95'][1]:+.3f} | {c['a_better']} | {c['b_better']} |"
            for c in results["comparisons"]) + "\n",
        "## Filter\n",
        "| Split | Questions | Company recognized | Filtered | Right filing kept | "
        "Filings left (mean) |\n|---|---|---|---|---|---|\n"
        + "\n".join(
            f"| {name} | {f['n']} | {f['company_found']} | {f['filtered']} | "
            f"{f['gold_filing_kept']} | {f['mean_filings_after']:.1f} |"
            for name, f in results["filter"].items()) + "\n",
    ]
    tax = results["taxonomy"]["test"]
    parts += [
        f"## Misses of `{tax['config']}` on test ({tax['misses']} of {tax['questions']})\n",
        "| Category | Count | Examples |\n|---|---|---|\n"
        + "\n".join(f"| {k} | {v} | {', '.join(tax['examples'][k][:3])} |"
                    for k, v in tax["counts"].items()) + "\n",
        "## By question type (test, headline vs. BM25 without a filter)\n",
        "| Type | n | Hit@10 | MRR@10 | BM25 no-filter Hit@10 |\n|---|---|---|---|---|\n"
        + "\n".join(
            f"| {t} | {v['n']} | {v['headline']['hit@10']:.2f} | {v['headline']['mrr@10']:.3f} | "
            f"{v['bm25/none']['hit@10']:.2f} |" for t, v in results["by_type"].items()) + "\n",
    ]
    if results.get("encode_latency"):
        e = results["encode_latency"]
        parts.append(f"MiniLM query encoding: p50 {e['p50_ms']:.1f} ms, p95 {e['p95_ms']:.1f} ms "
                     f"(included in dense and hybrid latency above).\n")
    Path(path).write_text("\n".join(parts), encoding="utf8")
